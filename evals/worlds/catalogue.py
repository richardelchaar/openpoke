"""The kinds of work an agent can hold, each with the wording a user would use for it.

A kind is a template. The generator fills it with a person and a detail to make one
piece of work, which is one agent. Two kinds in the same `family` share vocabulary
("claim", "quote"), so the generator never gives both to the same person or to two
people with the same first name: a topical follow-up has to point at one of them.

Placeholders: {who} the person as the user refers to them, {full} their full name,
{d} the detail. Each ask is (text, risk) where risk is "send" or "read".
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import List, Optional, Tuple


@dataclass(frozen=True)
class Kind:
    key: str
    family: str
    group: str          # client | vendor | colleague | personal
    label: str          # how the record names the work
    alias: str          # how a user might say it in other words
    subject: str        # email subject of the thread
    details: Tuple[str, ...]
    start: str          # the first request, which creates the agent
    asks: Tuple[Tuple[str, str], ...]
    summary: str
    third: Optional[str] = None   # a shared contact copied on the thread


def _k(key, family, group, label, alias, subject, details, start, asks, summary, third=None) -> Kind:
    return Kind(key, family, group, label, alias, subject, tuple(details), start, tuple(asks), summary, third)


